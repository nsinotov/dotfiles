# shellcheck shell=bash
# Sourced by install.sh — output, linking and code-generation helpers

# ------------------------------------
# Output and file helpers
# ------------------------------------

info()    { printf "  \033[1;34m%-50s\033[0m %s\n" "$1" "$2"; }
success() { printf "  \033[1;32m%-50s\033[0m %s\n" "$1" "OK"; }
fail()    { printf "  \033[1;31m%-50s\033[0m %s\n" "$1" "$2"; }

# Resolve target path: real system path or build/ in test mode
target_path() {
  local path="$1"
  if [ "$TEST_MODE" = true ]; then
    # Strip $HOME prefix and place under build/
    echo "$BUILD_DIR${path#"$HOME"}"
  else
    echo "$path"
  fi
}

link_file() {
  local src="$1" dst
  dst="$(target_path "$2")"

  if [ "$TEST_MODE" = true ]; then
    mkdir -p "$(dirname "$dst")"
    # In test mode, copy instead of symlink
    if [ -d "$src" ]; then
      cp -R "$src" "$dst"
    else
      cp "$src" "$dst"
    fi
    success "$dst" "(copied)"
    return
  fi

  if [ -L "$dst" ] && [ "$(readlink "$dst")" = "$src" ]; then
    success "$dst" ""
    return
  fi

  if [ -e "$dst" ] || [ -L "$dst" ]; then
    mv "$dst" "${dst}${BACKUP_SUFFIX}"
    info "$dst" "backed up"
  fi

  mkdir -p "$(dirname "$dst")"
  ln -s "$src" "$dst"
  success "$dst" ""
}

write_file() {
  local dst
  dst="$(target_path "$1")"
  mkdir -p "$(dirname "$dst")"
  cat > "$dst"
  success "$dst" ""
}

# shq <string> — single-quote for safe embedding in generated shell code
shq() {
  local q="'\\''"
  printf "'%s'" "${1//\'/$q}"
}

# emit_alias <name> <command> — append a quoted alias line to $outfile
emit_alias() {
  printf 'alias %s=%s\n' "$1" "$(shq "$2")" >> "$outfile"
}

# emit_doc <desc> <usage> [kind:text ...] — doc markers for the `dotfiles`
# command, written to $outfile above the next generated alias or function.
# kind is arg, detail or example.
emit_doc() {
  local desc="$1" usage="$2" item
  shift 2
  {
    echo ""
    echo "# desc: $desc"
    [ -n "$usage" ] && echo "# usage: $usage"
    for item in "$@"; do
      [ -n "$item" ] && echo "# ${item%%:*}: ${item#*:}"
    done
  } >> "$outfile"
  return 0
}

# emit_simple <suffix> <desc> <raw cmd> <final cmd> <pretest-gated 0/1> <gets env 0/1>
# — documented pass-through alias <project>-<suffix> (uses $name, $doc_pretest, $doc_env)
emit_simple() {
  [ -n "$4" ] || return 0
  emit_doc "$2" "[args]" "detail:Runs: $3" \
    "$([ "$5" = 1 ] && printf '%s' "$doc_pretest")" "$([ "$6" = 1 ] && printf '%s' "$doc_env")" \
    "detail:Extra arguments are appended to the command." "example:${name}-$1"
  emit_alias "${name}-$1" "$4"
}

# confirm "<question>" — yes/no prompt; always yes with --yes
confirm() {
  [ "$ASSUME_YES" = true ] && return 0
  local answer
  printf "  %s [y/N] " "$1"
  read -r answer
  [[ "$answer" =~ ^[Yy]$ ]]
}

# have "cmd|/abs/path|..." — true when any alternative is a command or an existing path
have() {
  local c
  local IFS='|'
  for c in $1; do
    if [[ "$c" == /* ]]; then
      [ -e "$c" ] && return 0
    else
      command -v "$c" > /dev/null 2>&1 && return 0
    fi
  done
  return 1
}

# link_if <module> <src> <dst> — link when the module is enabled, otherwise
# remove a link to <src> left over from an earlier install
link_if() {
  local module="$1" src="$2" dst="$3"
  if module_enabled "$module"; then
    link_file "$src" "$dst"
  elif [ "$TEST_MODE" = false ] && [ -L "$dst" ] && [ "$(readlink "$dst")" = "$src" ]; then
    rm "$dst"
    info "$dst" "unlinked (module $module disabled)"
  fi
  return 0
}

# kbd_link <module> <src> <dst> — Cyrillic include for a tool, linked only when
# both the tool's module and keyboard-ua-ru are enabled (the tracked configs
# load it with "source-file -q" / "config-file = ?")
kbd_link() {
  local module="$1" src="$2" dst="$3"
  if module_enabled keyboard-ua-ru && module_enabled "$module"; then
    link_file "$src" "$dst"
  elif [ "$TEST_MODE" = false ] && [ -L "$dst" ]; then
    rm "$dst"
    info "$dst" "unlinked (keyboard-ua-ru or $module disabled)"
  fi
  return 0
}

# link_or_merge <module> <src> <dst> <local-file> — link <src> when the module
# is enabled; when <local-file> exists, generate <dst> as <src> + local file
# instead (for per-machine additions such as extra tables). A disabled module
# removes the link or generated file.
link_or_merge() {
  local module="$1" src="$2" dst="$3" local_file="$4" target
  target="$(target_path "$dst")"
  if ! module_enabled "$module"; then
    if [ "$TEST_MODE" = false ] && { { [ -L "$dst" ] && [ "$(readlink "$dst")" = "$src" ]; } ||
       { [ -f "$dst" ] && grep -q "^# Auto-generated by install.sh" "$dst"; }; }; then
      rm "$dst"
      info "$dst" "removed (module $module disabled)"
    fi
    return 0
  fi
  if [ ! -f "$local_file" ]; then
    link_file "$src" "$dst"
    return 0
  fi
  # Remove an earlier symlink so write_file doesn't write through it into the repo
  [ -L "$target" ] && rm "$target"
  {
    echo "# Auto-generated by install.sh — do not edit"
    echo "# Sources: ${src#"$DOTFILES_DIR/"} + ${local_file/#$HOME/~}"
    echo ""
    cat "$src"
    echo ""
    echo "# ------------------------------------"
    echo "# Local additions (${local_file##*/})"
    echo "# ------------------------------------"
    echo ""
    cat "$local_file"
  } | write_file "$dst"
}

# feature_link <on|off> <src> <dst> — link an optional include when on,
# otherwise remove a link to it left over from an earlier install
feature_link() {
  local state="$1" src="$2" dst="$3"
  if [ "$state" = on ]; then
    link_file "$src" "$dst"
  elif [ "$TEST_MODE" = false ] && [ -L "$dst" ]; then
    rm "$dst"
    info "$dst" "unlinked (feature disabled)"
  fi
  return 0
}

# lua_list <words...> — a Lua list literal of quoted strings
lua_list() {
  local item out=""
  for item in "$@"; do
    item="${item//\\/\\\\}"
    out="$out\"${item//\"/\\\"}\", "
  done
  printf '{ %s}' "$out"
}
