# Auto-generated by install.sh — do not edit
# Helpers for killing processes on specific ports before starting servers

_free_port() {
  local port=$1 pids
  pids=$(lsof -ti :"$port" -sTCP:LISTEN 2>/dev/null) || return 0
  printf "\033[1;33m⚠ Port %s in use (PID %s) — killing…\033[0m\n" "$port" "${pids//$'\n'/, }"

  # Walk up the process tree from each listener to collect parent processes
  # (e.g. nx → remix → node). Stops at shells, multiplexers, and system processes
  # so the whole server tree is killed and the other terminal returns to a prompt.
  local kill_pids="$pids"
  for pid in ${pids}; do
    local cur=$pid
    while true; do
      local ppid
      ppid=$(ps -o ppid= -p "$cur" 2>/dev/null | tr -d ' ')
      [[ -z "$ppid" || "$ppid" -le 1 ]] && break
      local pcmd
      pcmd=$(ps -o comm= -p "$ppid" 2>/dev/null)
      [[ -z "$pcmd" ]] && break
      case "$pcmd" in
        zsh|-zsh|bash|-bash|fish|sh|dash|ksh|login|sshd|tmux*|screen*) break ;;
      esac
      kill_pids="$kill_pids $ppid"
      cur=$ppid
    done
  done

  kill $(echo "$kill_pids" | tr ' ' '\n' | sort -un | tr '\n' ' ') 2>/dev/null
  local i=0
  while lsof -ti :"$port" -sTCP:LISTEN &>/dev/null && (( i++ < 5 )); do sleep 0.2; done
  pids=$(lsof -ti :"$port" -sTCP:LISTEN 2>/dev/null) || return 0
  kill -9 $pids 2>/dev/null
  while lsof -ti :"$port" -sTCP:LISTEN &>/dev/null && (( i++ < 10 )); do sleep 0.2; done
}

# Kill orphaned processes (PPID=1) whose command line matches the given string.
# Catches leaked wrappers (e.g. nx) that survive after their child listener dies.
_kill_orphan_cmd() {
  local pids
  pids=$(pgrep -f "$*" 2>/dev/null) || return 0
  local orphans=""
  for pid in $pids; do
    local ppid
    ppid=$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')
    [[ "$ppid" == "1" ]] && orphans="${orphans:+$orphans }$pid"
  done
  [[ -z "$orphans" ]] && return 0
  printf "\033[1;33m⚠ Killing orphaned process(es): %s\033[0m\n" "$orphans"
  kill $orphans 2>/dev/null
  sleep 0.3
  for pid in $orphans; do
    kill -0 "$pid" 2>/dev/null && kill -9 "$pid" 2>/dev/null
  done
}

# Usage: _run_on_port PORT [PORT...] -- COMMAND [ARGS...]
_run_on_port() {
  local ports=()
  while [[ $# -gt 0 && "$1" != "--" ]]; do ports+=("$1"); shift; done
  [[ "${1:-}" = "--" ]] && shift
  for p in "${ports[@]}"; do _free_port "$p"; done
  _kill_orphan_cmd "$@"

  "$@"
  local rc=$?

  if (( rc == 143 || rc == 137 )); then
    printf "\n\033[1;33m⚠ Server stopped — port reclaimed by another instance.\033[0m\n"
  fi
  return $rc
}
