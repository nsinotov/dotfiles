# shellcheck shell=bash
# Sourced by install.sh — symlink configs

# ===========================================
# Phase 2: Symlink static configs
# ===========================================

echo ""
echo "Linking static configs..."
echo ""

link_if zsh      "$DOTFILES_DIR/shell/.zshrc"                 "$HOME/.zshrc"
link_if tmux     "$DOTFILES_DIR/tmux/.tmux.conf"              "$HOME/.tmux.conf"
link_if ghostty  "$DOTFILES_DIR/terminal/ghostty/config"      "$HOME/.config/ghostty/config"
link_if nvim     "$DOTFILES_DIR/editor/nvim"                  "$HOME/.config/nvim"
link_if sesh     "$DOTFILES_DIR/tools/sesh.toml"              "$HOME/.config/sesh/sesh.toml"

# Per-machine additions (e.g. Starship profile aliases, AeroSpace app rules)
# are appended from untracked *.local.toml files in the config dir
link_or_merge starship "$DOTFILES_DIR/prompt/starship.toml" "$HOME/.config/starship.toml" \
  "$DOTFILES_CONFIG_HOME/starship.local.toml"
if [ "$OS" = "Darwin" ]; then
  link_or_merge aerospace "$DOTFILES_DIR/tools/aerospace.toml" "$HOME/.aerospace.toml" \
    "$DOTFILES_CONFIG_HOME/aerospace.local.toml"
fi

# Optional includes, loaded by the tracked configs only when linked
kbd_link tmux    "$DOTFILES_DIR/tmux/keyboard-ua-ru.conf"     "$HOME/.config/tmux/keyboard-ua-ru.conf"
kbd_link ghostty "$DOTFILES_DIR/terminal/ghostty/keyboard-ua-ru" "$HOME/.config/ghostty/keyboard-ua-ru"
# F12 nested-tmux toggle: for workstations that SSH into remote tmux; set
# TMUX_NESTED_TOGGLE=false on servers so a double F12 can't lock both ends
nested_toggle=off
module_enabled tmux && [ "${TMUX_NESTED_TOGGLE:-true}" != false ] && nested_toggle=on
feature_link "$nested_toggle" "$DOTFILES_DIR/tmux/nested-toggle.conf" "$HOME/.config/tmux/nested-toggle.conf"

# Settings for tools that can't read config.sh (nvim: modules, local dirs, extras)
# shellcheck disable=SC2086  # word lists
{
  echo "-- Auto-generated by install.sh — do not edit"
  echo "return {"
  echo "  modules = $(lua_list $DOTFILES_MODULES),"
  echo "  local_dirs = $(lua_list $DOTFILES_LOCAL_DIRS),"
  echo "  nvim_extras = $(lua_list ${NVIM_EXTRAS:-}),"
  echo "  nvim_plugins = $(lua_list ${NVIM_PLUGINS:-}),"
  echo "}"
} | write_file "${XDG_STATE_HOME:-$HOME/.local/state}/dotfiles/settings.lua"
# Replaced by settings.lua in this version
[ "$TEST_MODE" = false ] && rm -f "${XDG_STATE_HOME:-$HOME/.local/state}/dotfiles/modules"

# Git's default global ignore path, so a personal ~/.gitignore stays untouched
link_if git      "$DOTFILES_DIR/git/.gitignore"               "$HOME/.config/git/ignore"
# Migration: drop the old ~/.gitignore link from earlier versions of this repo
if [ "$TEST_MODE" = false ] && [ -L "$HOME/.gitignore" ] &&
   [ "$(readlink "$HOME/.gitignore")" = "$DOTFILES_DIR/git/.gitignore" ]; then
  rm "$HOME/.gitignore"
  info "$HOME/.gitignore" "removed old link (now ~/.config/git/ignore)"
fi

# Fetch the plugins listed in .tmux.conf right away instead of prefix+I.
# Runs after linking, because TPM reads the plugin list from ~/.tmux.conf.
if [ "$TPM_FRESH" = true ] && [ -x "$TPM_DIR/bin/install_plugins" ] && have tmux; then
  TMUX_PLUGIN_MANAGER_PATH="$HOME/.tmux/plugins/" "$TPM_DIR/bin/install_plugins" > /dev/null &&
    success "tmux plugins" "installed"
fi

# Custom scripts (~/bin/)
link_if vpn "$DOTFILES_DIR/tools/vpn" "$HOME/bin/vpn"
